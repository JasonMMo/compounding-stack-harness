def _make_slug(company: str, industry: str) -> str:
    """회사명+업종으로 ASCII slug 생성."""
    base = company if company else industry if industry else "client"
    # 한글/특수문자 → 제거, 공백→하이픈
    slug = re.sub(r"[^\w\s-]", "", base)
    slug = re.sub(r"[\s_]+", "-", slug)
    slug = re.sub(r"[^a-zA-Z0-9-]", "", slug)
    slug = slug.strip("-").lower()
    if not slug:
        slug = "client"
    return slug[:40]  # 너무 길면 자름

# ---------------------------------------------------------------------------
# profile YAML 직렬화 (PyYAML 없이 간단한 포맷)
# ---------------------------------------------------------------------------

def _yaml_str(val) -> str:
    if val is None:
        return "null"
    if isinstance(val, bool):
        return "true" if val else "false"
    if isinstance(val, (int, float)):
        return str(val)
    # 문자열: 특수문자 포함 시 quote
    if any(c in str(val) for c in [":", "#", "[", "]", "{", "}", "&", "*", "!", "|", ">", "'"]):
        return f'"{val}"'
    return str(val)


def _render_profile(data: dict) -> str:
    """profile dict → YAML 문자열 (최소 직렬화)."""
    lines = [
        f"# profiles/{data['customer']['slug']}.draft.yaml",
        f"# auto-generated by intake_to_profile.py — review before use",
        f"version: 1",
        "",
        "customer:",
        f"  slug: {data['customer']['slug']}",
        f"  display: {_yaml_str(data['customer']['display'])}",
        f"  status: draft",
    ]
    if data["customer"].get("contact"):
        lines.append(f"  contact: {data['customer']['contact']}")
    if data["customer"].get("industry"):
        lines.append(f"  industry: {data['customer']['industry']}")
    lines.append("")

    # stack
    lines.append("stack:")
    if data.get("stack", {}).get("frontend"):
        lines.append(f"  frontend: {data['stack']['frontend']}")
    else:
        lines.append("  frontend: null  # 미결정 — needs note 참조")
    if data.get("stack", {}).get("backend"):
        lines.append(f"  backend: {data['stack']['backend']}")
    else:
        lines.append("  backend: null   # 미결정 — needs note 참조")
    lines.append("")

    # ddl
    lines.append("ddl:")
    if data.get("ddl", {}).get("dialect"):
        lines.append(f"  dialect: {data['ddl']['dialect']}")
    else:
        lines.append("  dialect: postgres  # 기본 권장 — 확인 필요")
    lines.append(f"  schema: {data['customer']['slug']}")
    lines.append("  idempotent_strategy: on_conflict")
    lines.append("")

    # domains
    if data.get("domains"):
        lines.append("domains:")
        for d in data["domains"]:
            lines.append(f"  - slug: {d['slug']}")
            lines.append(f"    display: {_yaml_str(d['display'])}")
            lines.append(f"    entities: [{', '.join(d['entities'])}]")
            lines.append(f"    seen_at: {date.today().isoformat()}")
        lines.append("")

    # datasource 기본값
    lines.append("datasource:")
    lines.append(f"  username: ${{{data['customer']['slug'].upper().replace('-','_')}_DB_USER}}")
    lines.append(f"  password: ${{{data['customer']['slug'].upper().replace('-','_')}_DB_PASS}}")
    lines.append('  url_template: "jdbc:postgresql://{host}:{port}/{db}"')
    lines.append("  host: db.internal")
    lines.append("  port: 5432")
    lines.append(f"  db: {data['customer']['slug'].replace('-','_')}_prod")
    lines.append("")

    # overlay 기본값
    lines.append("overlay:")
    lines.append(f"  shell_app_id: {data['customer']['slug']}-portal")
    lines.append("  vault_agent: false")
    lines.append("  sso_keycloak: false")
    lines.append("")

    # defaults
    lines.append("defaults:")
    lines.append("  locale: ko-KR")
    lines.append("  timezone: Asia/Seoul")
    lines.append("")

    # billing
    lines.append("billing:")
    lines.append("  llm_budget_usd_per_month: 100")
    lines.append("  prepaid_credits_usd: 0")
    lines.append("")

    return "\n".join(lines)

