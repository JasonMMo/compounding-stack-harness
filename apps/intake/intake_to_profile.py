def convert(answers: dict) -> tuple[dict, list[str]]:
    """answers dict → (profile_data, extra_signals_for_needs_note)."""
    # 기존 저장분 bool 파싱 결함 정규화
    answers = _normalize_answers(answers)

    extra_signals: list[str] = []

    # 기본 정보
    company = answers.get("company_name", "").strip()
    industry_raw = answers.get("industry", "")
    industry = INDUSTRY_MAP.get(industry_raw, "generic")
    email = answers.get("contact_email", "").strip()

    slug = _make_slug(company, industry_raw)

    profile: dict = {
        "customer": {
            "slug": slug,
            "display": company or slug,
            "contact": email,
            "industry": industry,
        },
        "stack": {},
        "ddl": {},
        "domains": [],
    }

    # stack.frontend
    fe_raw = answers.get("it_frontend_pref", "")
    fe_mapped = FRONTEND_MAP.get(fe_raw)
    if fe_raw and fe_raw not in (None, "unknown", ""):
        if fe_mapped:
            profile["stack"]["frontend"] = fe_mapped
        else:
            extra_signals.append(f"stack.frontend 요청값: `{fe_raw}` — profile schema 미지원, 수동 확인 필요")

    # stack.backend
    be_raw = answers.get("it_backend_pref", "")
    be_mapped = BACKEND_MAP.get(be_raw)
    if be_raw and be_raw not in (None, "unknown", ""):
        if be_mapped:
            profile["stack"]["backend"] = be_mapped
        else:
            extra_signals.append(f"stack.backend 요청값: `{be_raw}` — profile schema 미지원, 수동 확인 필요")

    # ddl.dialect
    dialect_raw = answers.get("it_db_dialect", "")
    dialect_mapped = DIALECT_MAP.get(dialect_raw)
    if dialect_raw and dialect_raw not in (None, "unknown", ""):
        if dialect_mapped:
            profile["ddl"]["dialect"] = dialect_mapped
        else:
            extra_signals.append(
                f"ddl.dialect 요청값: `{dialect_raw}` — profile schema 미지원 (mssql/none_new 등). "
                f"수동으로 지원 dialect 확인 후 설정 필요."
            )

    # domains[].entities
    data_domains = answers.get("data_domains", [])
    today = date.today().isoformat()
    for d in data_domains:
        mapping = DOMAIN_ENTITY_MAP.get(d)
        if mapping is None:
            extra_signals.append(f"domains 요청: `{d}` — 카탈로그 없음, 담당자 수동 등록 필요")
            continue
        domain_slug, entities = mapping
        profile["domains"].append({
            "slug": domain_slug,
            "display": d,
            "entities": entities,
        })

    # 스키마 불일치 항목들 → extra_signals (profile에 넣지 않음)

    # billing.setup_cost_krw (questions에 있지만 profile schema에 없음)
    budget = answers.get("ceo_budget_setup", "")
    if budget and budget != "unknown":
        extra_signals.append(f"예산 범위: `{budget}` (billing.setup_cost_krw — profile schema v1 미정의, needs note 기재)")

    # datasource.self_host_required (스키마에 없는 형태)
    data_security = answers.get("ceo_data_security", "")
    if data_security and data_security != "unknown":
        extra_signals.append(
            f"데이터 보관 요건: `{data_security}` "
            f"(datasource.self_host_required 유사 — profile schema v1 해당 키 미정의, "
            f"인도 전 CISO 리뷰 시 활용)"
        )

    # datasource.host (it_server_env → 서버환경 radio, 직접 profile에 넣지 않음)
    server_env = answers.get("it_server_env", "")
    if server_env and server_env not in ("unknown", ""):
        extra_signals.append(
            f"서버 환경: `{server_env}` "
            f"(datasource.host 참고용 — 인도 시 실제 host/ip로 교체 필요)"
        )

    # overlay.sso_keycloak (auth_method → simple/sso/ldap)
    auth = answers.get("it_auth_method", "")
    if auth and auth != "unknown":
        if auth == "simple_session":
            extra_signals.append("인증: 단순 세션 로그인 (overlay.sso_keycloak=false 권장)")
        elif auth in ("sso_keycloak", "ldap"):
            extra_signals.append(
                f"인증: `{auth}` (overlay.sso_keycloak — M3 ops pack 기능, 인도 시 별도 설정)"
            )

    # overlay.vault_agent (docker_available)
    docker = answers.get("it_docker_available", "")
    if docker and docker != "unknown":
        extra_signals.append(
            f"Docker 가용성: `{docker}` "
            f"(overlay.vault_agent 연관 — M3 ops pack. 현재 false 기본값 유지)"
        )

    return profile, extra_signals

