def main() -> int:
    parser = argparse.ArgumentParser(
        description="intake revision JSON → profiles/<slug>.draft.yaml + needs note",
    )
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--revision", help="revision JSON 파일 경로")
    group.add_argument("--client-id", help="client_id (data-dir에서 최신 revision 사용)")

    parser.add_argument(
        "--data-dir",
        default=str(Path(__file__).parent / "data"),
        help="DATA_DIR (기본: apps/intake/data)",
    )
    parser.add_argument(
        "--out",
        default=None,
        help="출력 디렉터리 (기본: profiles/ 에 draft.yaml, stdout 에 needs note)",
    )
    args = parser.parse_args()

    # answers 로드
    if args.revision:
        rev_path = Path(args.revision)
        if not rev_path.exists():
            print(f"[intake_to_profile] ERROR: {rev_path} 없음", file=sys.stderr)
            return 1
        with open(rev_path, encoding="utf-8") as f:
            answers = json.load(f)
    else:
        # client-id 모드: 최신 revision 사용
        data_dir = Path(args.data_dir)
        rev_dir = data_dir / "clients" / args.client_id / "revisions"
        if not rev_dir.exists():
            print(f"[intake_to_profile] ERROR: revisions dir 없음: {rev_dir}", file=sys.stderr)
            return 1
        rev_files = sorted(rev_dir.glob("*.json"))
        if not rev_files:
            print(f"[intake_to_profile] ERROR: revision 없음", file=sys.stderr)
            return 1
        with open(rev_files[-1], encoding="utf-8") as f:
            answers = json.load(f)

    # 변환
    profile_data, extra_signals = convert(answers)
    slug = profile_data["customer"]["slug"]

    # profile YAML 저장
    profile_yaml = _render_profile(profile_data)
    if args.out:
        out_dir = Path(args.out)
        out_dir.mkdir(parents=True, exist_ok=True)
        profile_path = out_dir / f"{slug}.draft.yaml"
    else:
        profile_path = REPO_ROOT / "profiles" / f"{slug}.draft.yaml"

    profile_path.parent.mkdir(parents=True, exist_ok=True)
    profile_path.write_text(profile_yaml, encoding="utf-8")
    print(f"[intake_to_profile] profile 저장: {profile_path}")

    # needs note 출력/저장
    needs_note = _render_needs_note(slug, answers, extra_signals)
    if args.out:
        note_path = Path(args.out) / f"{slug}-needs-note.md"
        note_path.write_text(needs_note, encoding="utf-8")
        print(f"[intake_to_profile] needs note 저장: {note_path}")
    else:
        print("\n" + "=" * 60)
        print(needs_note)

    return 0


if __name__ == "__main__":
    sys.exit(main())
